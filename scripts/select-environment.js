#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import readline from 'readline';

const ENVIRONMENTS_FILE = path.join(process.cwd(), '.db-environments.json');
const CURRENT_ENV_FILE = path.join(process.cwd(), 'scripts', 'current-environment.json');
const ENV_LOCAL_FILE = path.join(process.cwd(), '.env.local');

/** Keys owned by this script — always rewritten from the selected DB environment. */
export const MANAGED_ENV_KEYS = [
  'VITE_SUPABASE_URL',
  'VITE_SUPABASE_PUBLISHABLE_KEY',
  'SUPABASE_URL',
  'SUPABASE_PUBLISHABLE_KEY',
  'SUPABASE_SECRET_KEY',
  'SUPABASE_SERVICE_ROLE_KEY',
];

// Load environments from db:util
function loadEnvironments() {
  try {
    if (fs.existsSync(ENVIRONMENTS_FILE)) {
      const data = fs.readFileSync(ENVIRONMENTS_FILE, 'utf8');
      const config = JSON.parse(data);
      // Return the environments array from the config object
      return config.environments || [];
    }
  } catch (error) {
    console.error('Error loading environments:', error);
  }
  return [];
}

/**
 * Parse KEY=VALUE lines from a .env-style file.
 * Ignores blank lines and full-line comments. Does not expand quotes.
 */
export function parseEnvFileContents(contents) {
  const vars = {};
  if (!contents) return vars;

  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) continue;
    vars[key] = line.slice(eq + 1);
  }
  return vars;
}

/**
 * Build .env.local body: managed Supabase keys from the selected environment,
 * plus any non-managed keys already present (brand, phone, etc.).
 */
export function buildEnvLocalContents(environment, existingContents = '') {
  const url = environment.supabaseUrl || '';
  const publishable =
    environment.supabasePublishableKey ||
    environment.publishableKey ||
    '';
  const secret =
    environment.supabaseSecretKey ||
    environment.serviceRoleKey ||
    environment.serviceKey ||
    environment.secretKey ||
    '';

  const existing = parseEnvFileContents(existingContents);
  const managed = {
    VITE_SUPABASE_URL: url,
    VITE_SUPABASE_PUBLISHABLE_KEY: publishable,
    SUPABASE_URL: url,
    SUPABASE_PUBLISHABLE_KEY: publishable,
    SUPABASE_SECRET_KEY: secret,
    SUPABASE_SERVICE_ROLE_KEY: secret,
  };

  const preservedKeys = Object.keys(existing)
    .filter((key) => !MANAGED_ENV_KEYS.includes(key))
    .sort();

  const lines = [
    '# Generated by scripts/select-environment.js — do not commit',
    `# Environment: ${environment.name || 'unknown'}`,
    '# Supabase keys below are rewritten on each env:select / npm run dev.',
    '# Other VITE_* overrides (logo, brand, phone, etc.) are preserved.',
    ...MANAGED_ENV_KEYS.map((key) => `${key}=${managed[key]}`),
  ];

  if (preservedKeys.length > 0) {
    lines.push('');
    lines.push('# Preserved local overrides (not managed by env:select)');
    for (const key of preservedKeys) {
      lines.push(`${key}=${existing[key]}`);
    }
  }

  lines.push('');
  return lines.join('\n');
}

function writeEnvLocal(environment) {
  if (environment?.type && environment.type !== 'supabase') {
    console.log('ℹ️  Skipping .env.local write (non-Supabase environment).');
    return;
  }
  if (!environment?.supabaseUrl) {
    console.warn('⚠️  Environment missing supabaseUrl; not writing .env.local');
    return;
  }
  const existingContents = fs.existsSync(ENV_LOCAL_FILE)
    ? fs.readFileSync(ENV_LOCAL_FILE, 'utf8')
    : '';
  fs.writeFileSync(ENV_LOCAL_FILE, buildEnvLocalContents(environment, existingContents));
  console.log(`📁 Vite/API env written to: ${ENV_LOCAL_FILE}`);
}

// Save current environment
function saveCurrentEnvironment(environment) {
  try {
    fs.writeFileSync(CURRENT_ENV_FILE, JSON.stringify(environment, null, 2));
    writeEnvLocal(environment);
    console.log(`✅ Environment '${environment.name}' selected successfully!`);
    console.log(`📁 Current environment saved to: ${CURRENT_ENV_FILE}`);
  } catch (error) {
    console.error('Error saving current environment:', error);
  }
}

// Display environments
function displayEnvironments(environments) {
  console.log('\n📋 Available Environments:');
  console.log('='.repeat(50));
  
  environments.forEach((env, index) => {
    const type = env.type === 'supabase' ? 'Supabase' : 'Local PostgreSQL';
    const url = env.type === 'supabase' && env.supabaseUrl 
      ? ` (${env.supabaseUrl.replace('https://', '').replace('.supabase.co', '')})`
      : '';
    
    console.log(`${index + 1}. ${env.name}`);
    console.log(`   Type: ${type}${url}`);
    console.log('');
  });
}

// Get current environment
function getCurrentEnvironment() {
  try {
    if (fs.existsSync(CURRENT_ENV_FILE)) {
      const data = fs.readFileSync(CURRENT_ENV_FILE, 'utf8');
      return JSON.parse(data);
    }
  } catch (error) {
    console.error('Error loading current environment:', error);
  }
  return null;
}

// Main function
async function main() {
  console.log('🔧 Metro Landmark - Environment Selector');
  console.log('='.repeat(50));
  
  const environments = loadEnvironments();
  console.log(`📊 Found ${environments.length} environments`);
  
  if (environments.length === 0) {
    console.log('❌ No environments found!');
    console.log('💡 Copy .db-environments.example.json to .db-environments.json and fill in values,');
    console.log('   or use the db:util tool:');
    console.log('   npm run db:util');
    process.exit(1);
  }
  
  const currentEnv = getCurrentEnvironment();
  console.log(`🔍 Current environment check:`, currentEnv ? currentEnv.name : 'None');
  
  // Check for --force flag to always show selection
  const forceSelection = process.argv.includes('--force') || process.argv.includes('-f');
  
  if (currentEnv && !forceSelection) {
    console.log(`📍 Current environment: ${currentEnv.name}`);
    // Ensure .env.local exists / stays in sync for Vite (no hardcoded key fallbacks).
    writeEnvLocal(currentEnv);
    console.log('✅ Environment already selected, starting app...\n');
    return; // Skip selection if environment already exists
  }
  
  if (forceSelection) {
    console.log('🔄 Force selection mode - showing all environments...\n');
  }
  
  displayEnvironments(environments);
  
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
  });
  
  const question = (prompt) => {
    return new Promise((resolve) => {
      rl.question(prompt, resolve);
    });
  };
  
  try {
    const answer = await question(`Select environment (1-${environments.length}): `);
    const index = parseInt(answer) - 1;
    
    if (index >= 0 && index < environments.length) {
      const selectedEnv = environments[index];
      saveCurrentEnvironment(selectedEnv);
      
      console.log('\n🚀 Environment selected! Starting app...\n');
    } else {
      console.log('❌ Invalid selection. Please run the script again.');
      process.exit(1);
    }
  } catch (error) {
    console.error('Error:', error);
    process.exit(1);
  } finally {
    rl.close();
  }
}

// Run when executed directly (avoid double-invoke from overlapping entry checks)
const isDirectRun =
  process.argv[1] &&
  (import.meta.url === `file://${process.argv[1]}` ||
    process.argv[1].endsWith('select-environment.js'));

if (isDirectRun) {
  main().catch(console.error);
}

export { loadEnvironments, saveCurrentEnvironment, getCurrentEnvironment, writeEnvLocal };
